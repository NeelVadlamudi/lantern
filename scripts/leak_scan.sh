#!/usr/bin/env bash
# Leak scan: fails (exit 1) when a file that is committed or published contains something that
# should not be public. Run by CI (dbt_ci.yml), by the daily refresh before publishing, and as a
# git pre-commit hook (.githooks/pre-commit; enable with `git config core.hooksPath .githooks`).
#
#   scripts/leak_scan.sh            scan the files git tracks (staged state included)
#   scripts/leak_scan.sh DIR ...    scan every file under DIR (e.g. out/ or _site/ before publishing)
#
# Checks, each with its own label in the output:
#   local-path   home, temp and workspace paths from a developer machine
#   email        any email address except GitHub noreply addresses
#   secret       API keys, tokens and private key blocks
#   symlink      symbolic links (tracked or in the scanned folder)
#   debug        a debug switch left on
#   wording      tool or assistant wording that does not belong in the project (skipped for
#                third-party bundles: the generated dbt docs app and assets/vendor/, whose
#                library code trips the wording patterns)
# This file holds the patterns themselves, so it is skipped.

self="scripts/leak_scan.sh"
status=0

if [ "$#" -eq 0 ] && ! git rev-parse --is-inside-work-tree > /dev/null 2>&1; then
    set -- .
fi

if [ "$#" -eq 0 ]; then
    mapfile -d '' files < <(git ls-files -z --cached)
    while IFS= read -r line; do
        echo "symlink: ${line#*$'\t'}"
        status=1
    done < <(git ls-files -s | awk '$1 == "120000"')
else
    files=()
    for dir in "$@"; do
        while IFS= read -r -d '' f; do files+=("${f#./}"); done < <(find "$dir" -type f -not -path '*/.git/*' -print0)
        while IFS= read -r -d '' link; do
            echo "symlink: $link"
            status=1
        done < <(find "$dir" -type l -print0)
    done
fi

scan() {
    local label="$1" pattern="$2" exclude="${3:-}" skip_path="${4:-}"
    local hits
    for f in "${files[@]}"; do
        [ "$f" = "$self" ] && continue
        if [ -n "$skip_path" ] && [[ "$f" =~ $skip_path ]]; then continue; fi
        [ -f "$f" ] || continue
        if [ -n "$exclude" ]; then
            hits=$(grep -I -n -i -E -e "$pattern" -- "$f" 2>/dev/null | grep -v -i -E -e "$exclude")
        else
            hits=$(grep -I -n -i -E -e "$pattern" -- "$f" 2>/dev/null)
        fi
        if [ -n "$hits" ]; then
            while IFS= read -r h; do echo "$label: $f:${h:0:200}"; done <<< "$hits"
            status=1
        fi
    done
}

scan local-path '(/home/[a-z0-9_-]+/|/Users/[A-Za-z0-9_-]+/|(^|[^a-z0-9_])/tmp/|/workspace/|[A-Z]:\\\\Users\\\\)'
scan email '[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}' '@users\.noreply\.github\.com|git@github\.com'
scan secret '(gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|AKIA[0-9A-Z]{16}|xox[abpr]-[A-Za-z0-9-]{10,}|sk-[A-Za-z0-9]{20,}|-----BEGIN [A-Z ]*PRIVATE KEY-----|(api[_-]?key|secret|token|password)["'"'"' ]*[:=] *["'"'"'][A-Za-z0-9/+_-]{16,})'
scan debug '(^|[^a-z_])(debug *[:=] *(true|1|on|yes)|--debug([^-a-z]|$)|set -x$|DBT_DEBUG)'
scan wording '(cursor|grok|chatgpt|openai|anthropic|claude|copilot|gemini|\bllm\b|large language model|ai[- ]generated|generated by|written by an? (ai|assistant|bot)|as an ai)' '' '(^|/)dbt/index\.html$|(^|/)assets/vendor/'

if [ "$status" -ne 0 ]; then
    echo "leak scan: FAILED"
else
    echo "leak scan: clean (${#files[@]} files)"
fi
exit "$status"
